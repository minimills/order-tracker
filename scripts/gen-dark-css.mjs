#!/usr/bin/env node
/**
 * Writes src/dark.css: the Dark theme.
 *
 * The screens are written with light colours (bg-white, text-slate-900,
 * bg-amber-50 …). This script finds every colour class used in src/ and
 * writes a matching dark colour for it, active only when <html> has the class
 * "dark" (Settings → Theme). Strong colours (buttons, badges: shade 400 and
 * up as backgrounds) stay as they are; light tints become dark tints, dark
 * text becomes light text.
 *
 * Elements inside `.keep-light` (sticky notes, printouts, signature pads) and
 * `.keep-dark` (the sidebar) keep their own colours.
 *
 * Runs before every build (npm run build) and with `npm run gen:dark`.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
// Tailwind's own colour values (pages only include the variables they use, so values are written out).
const PALETTE = Object.fromEntries(
  [...readFileSync(join(root, 'node_modules/tailwindcss/theme.css'), 'utf8').matchAll(/--color-([a-z]+-\d+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]),
)
const c = (family, shade) => PALETTE[`${family}-${shade}`] ?? `var(--color-${family}-${shade})`

// Dark surfaces (slate based).
const PAGE = '#0b1220'
const CARD = '#131c2e'
const NEUTRAL = {
  bg: { white: CARD, 50: PAGE, 100: '#1c2638', 200: '#263247', 300: '#334155', 400: '#475569', 700: '#cbd5e1', 800: '#e2e8f0', 900: '#f1f5f9' },
  text: { black: '#f8fafc', 950: '#f8fafc', 900: '#f1f5f9', 800: '#e2e8f0', 700: '#cbd5e1', 600: '#a7b3c4', 500: '#8b97a8', 400: '#6b778a', 300: '#475569' },
  border: { 50: '#172033', 100: '#1a2436', 200: '#263247', 300: '#334155', 400: '#475569', 500: '#64748b', 800: '#cbd5e1', 900: '#e2e8f0' },
}
const NEUTRALS = new Set(['slate', 'gray', 'zinc', 'neutral', 'stone'])
const mix = (family, pct, base = CARD) => `color-mix(in srgb, ${c(family, 500)} ${pct}%, ${base})`

/** The dark value for one colour utility, or null to leave it alone. */
function darkValue(kind, family, shade) {
  const n = Number(shade)
  if (family === 'white') {
    if (kind === 'bg') return CARD
    if (kind === 'border' || kind === 'divide') return NEUTRAL.border[200]
    return null
  }
  if (family === 'black') return kind === 'text' ? NEUTRAL.text.black : null
  if (NEUTRALS.has(family)) {
    if (kind === 'bg') return NEUTRAL.bg[n] ?? null
    if (kind === 'text') return NEUTRAL.text[n] ?? null
    if (kind === 'border' || kind === 'divide' || kind === 'ring' || kind === 'outline') return NEUTRAL.border[n] ?? null
    return null
  }
  if (kind === 'bg') return n <= 300 ? mix(family, { 50: 14, 100: 22, 200: 32, 300: 42 }[n]) : null
  if (kind === 'text') return n >= 800 ? c(family, 200) : n === 700 ? c(family, 300) : n === 600 ? c(family, 400) : null
  if (kind === 'border' || kind === 'divide' || kind === 'ring' || kind === 'outline') return n <= 300 ? mix(family, 45) : null
  return null
}

const PROP = {
  bg: (v) => `background-color: ${v}`,
  text: (v) => `color: ${v}`,
  border: (v) => `border-color: ${v}`,
  ring: (v) => `--tw-ring-color: ${v}`,
  outline: (v) => `outline-color: ${v}`,
  divide: (v) => `border-color: ${v}`,
}
const VARIANT = { '': '', 'hover:': ':hover', 'focus:': ':focus', 'disabled:': ':disabled', 'group-hover:': '' }

// Find every colour class in src/.
const RE = /(?<![\w-])((?:hover:|focus:|disabled:|group-hover:)?)(bg|text|border|ring|outline|divide)-(white|black|slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)(?:-(\d{2,3}))?(?:\/(\d{1,3}))?(?![\w-])/g
const files = []
;(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p)
    else if (/\.(tsx?|css)$/.test(name) && !name.endsWith('dark.css')) files.push(p)
  }
})(join(root, 'src'))

const rules = new Map() // declaration -> selectors
for (const f of files) {
  for (const m of readFileSync(f, 'utf8').matchAll(RE)) {
    const [token, variant, kind, family, shade, alpha] = m
    if (!shade && family !== 'white' && family !== 'black') continue
    let value = darkValue(kind, family, shade)
    if (!value) continue
    if (alpha) value = `color-mix(in srgb, ${value} ${alpha}%, transparent)`
    const cls = '.' + token.replace(/[:/]/g, (c) => '\\' + c)
    let sel = variant === 'group-hover:' ? `.group:hover ${cls}` : `${cls}${VARIANT[variant]}`
    if (kind === 'divide') sel = `${cls} > :not(:last-child)`
    const decl = PROP[kind](value)
    if (!rules.has(decl)) rules.set(decl, new Set())
    rules.get(decl).add(sel)
  }
}

const NOT = ':not(:is(.keep-light, .keep-light *, .keep-dark, .keep-dark *))'
let css = `/* Generated by scripts/gen-dark-css.mjs – do not edit by hand (npm run gen:dark). */
@media screen {
  html.dark { color-scheme: dark; }
  html.dark body { background-color: ${PAGE}; color: ${NEUTRAL.text[900]}; }
  /* Primary buttons (dark on light) become light on dark. */
  html.dark :is(.bg-slate-900, .bg-slate-800, .bg-slate-700).text-white${NOT},
  html.dark :is(.bg-slate-900, .bg-slate-800, .bg-slate-700) .text-white${NOT} { color: ${PAGE}; }
`
for (const [decl, sels] of [...rules].sort((a, b) => a[0].localeCompare(b[0]))) {
  const list = [...sels].sort()
  css += `  html.dark :is(${list.join(', ')})${NOT} { ${decl}; }\n`
}
css += '}\n'
writeFileSync(join(root, 'src/dark.css'), css)
console.log(`✓ Dark theme: ${[...rules.values()].reduce((n, s) => n + s.size, 0)} colour classes mapped (src/dark.css).`)
